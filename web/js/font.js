const CHARS = Object.keys(G);
const CW = 6; // advance (5px glyph + 1px spacing)

const atlases = {};
function atlas(color) {
  if (atlases[color]) return atlases[color];
  const c = document.createElement('canvas');
  c.width = CHARS.length * CW;
  c.height = 7;
  const ctx = c.getContext('2d');
  ctx.fillStyle = color;
  CHARS.forEach((ch, i) => {
    G[ch].split('|').forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '#') ctx.fillRect(i * CW + x, y, 1, 1);
    });
  });
  return (atlases[color] = c);
}
const index = Object.fromEntries(CHARS.map((c, i) => [c, i]));

export function textWidth(s) { return s.length * CW - 1; }

export function drawText(ctx, s, x, y, color = '#ffffff', shadow = '#1a1430') {
  s = String(s);
  x = Math.round(x); y = Math.round(y);
  for (const [col, dx] of shadow ? [[shadow, 1], [color, 0]] : [[color, 0]]) {
    const a = atlas(col);
    for (let i = 0; i < s.length; i++) {
      let ch = s[i];
      if (index[ch] === undefined) ch = ch.toUpperCase();
      const gi = index[ch];
      if (gi === undefined) continue;
      ctx.drawImage(a, gi * CW, 0, 5, 7, x + i * CW + dx, y + dx, 5, 7);
    }
  }
}

export function drawTextCentered(ctx, s, cx, y, color, shadow) {
  drawText(ctx, s, cx - textWidth(String(s)) / 2, y, color, shadow);
}
